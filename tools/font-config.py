#!/usr/bin/env python3
"""The font configuration, from the one size table (#62).

    python3 tools/font-config.py write              (make fonts, first: the configuration)
    python3 tools/font-config.py advances <dir>...  (make fonts, after the scaler: true advances)

`resources/fonts/sizes.json` lists every font the app has: its weight, its size as a share of the
screen's width, its pixels at the 416 px reference, and which glyphs it holds. `write` makes from it
what garmin-font-scaler and the app read: `resources/fonts/fonts.xml` (one font per size, the
scaler's `jsonData`), `resources/fonts/charsets.json`, and `source/FontSizes.mc` (the shares and the
resource ids, for `Fonts` in `Draw.mc`). None of the three is edited by hand; `check-font-config.py`
holds them to the table.

`advances` rewrites each bitmap's `xadvance` to the font's advance at its size, rounded to the
nearest pixel: ttf2bmp rounds every advance up, which made a line of text about half a pixel per
glyph wider on the watch than in the mocks (a browser lays text out with the exact advances). The
glyph cells and the atlas are left as they are. Reads the TTF's own tables: pure Python, no fontTools.
"""
import json
import math
import os
import re
import struct
import sys

SIZES = 'resources/fonts/sizes.json'
FACE = 'BarlowCondensedTabular-{weight}'


def table():
    with open(SIZES, encoding='utf-8') as f:
        doc = json.load(f)
    return doc


def font_id(f):
    return f"{f['weight']}{f['px']}"


def fonts_xml(doc):
    rows = '\n'.join(f'        <font id="{font_id(f)}" filename="{FACE.format(weight=f["weight"])}-{f["px"]}.fnt" '
                     f'antialias="true" />' for f in doc['fonts'])
    return f"""<resources>

    <!-- Generated by tools/font-config.py from sizes.json, the size table (#62): do not edit. Barlow
         Condensed with tabular figures, SemiBold and Bold, each at its share of the screen's width,
         here in pixels at the reference resolution, {doc['reference']}x{doc['reference']} (resolutions.json);
         garmin-font-scaler generates the bitmaps. See README.md, Fonts. -->
    <fonts>
{rows}
    </fonts>

    <jsonData id="FontCharsets" filename="charsets.json"/>
    <jsonData id="ScreenResolutions" filename="resolutions.json" />

</resources>
"""


def charsets_json(doc):
    sets = [{"fontCharset": doc['glyphs'][f['glyphs']], "fontId": font_id(f)} for f in doc['fonts']]
    return json.dumps(sets, indent=4, ensure_ascii=False) + '\n'


def sizes_mc(doc):
    def shares(w):
        return ', '.join(f"{f['share']:.4f}" for f in doc['fonts'] if f['weight'] == w)

    def ids(w):
        return ', '.join(f"Rez.Fonts.{font_id(f)}" for f in doc['fonts'] if f['weight'] == w)

    def wrap(text, indent):
        out, line = [], ''
        for word in text.split(' '):
            if len(indent) + len(line) + len(word) + 1 > 104 and line:
                out.append(line.rstrip())
                line = ''
            line += word + ' '
        out.append(line.rstrip())
        return ('\n' + indent).join(out)

    return f"""import Toybox.Lang;

// Generated by tools/font-config.py from resources/fonts/sizes.json, the size table (#62): do not edit.
// The app's font sizes, as shares of the screen's width, smallest first, and their resource ids.
module FontSizes {{

    const SEMI = [{wrap(shares('SemiBold'), '        ')}] as Array<Float>;
    const BOLD = [{wrap(shares('Bold'), '        ')}] as Array<Float>;

    function semiId(i as Number) as ResourceId {{
        return ([{wrap(ids('SemiBold'), '            ')}] as Array<ResourceId>)[i];
    }}

    function boldId(i as Number) as ResourceId {{
        return ([{wrap(ids('Bold'), '            ')}] as Array<ResourceId>)[i];
    }}
}}
"""


OUTPUTS = {'resources/fonts/fonts.xml': fonts_xml, 'resources/fonts/charsets.json': charsets_json,
           'source/FontSizes.mc': sizes_mc}


def problems(doc):
    """What is wrong with the table itself."""
    out = []
    ref = doc['reference']
    for f in doc['fonts']:
        if round(f['share'] * ref) != f['px'] or abs(f['share'] - round(f['px'] / ref, 4)) > 1e-9:
            out.append(f"{font_id(f)}: share {f['share']} is not {f['px']} px over {ref}, to four places")
        if f['glyphs'] not in doc['glyphs']:
            out.append(f"{font_id(f)}: no glyph set {f['glyphs']!r}")
    for w in sorted({f['weight'] for f in doc['fonts']}):
        px = [f['px'] for f in doc['fonts'] if f['weight'] == w]
        if px != sorted(set(px)):
            out.append(f"{w}: sizes not rising, or one twice (the scaler names a bitmap by face and size)")
    return out


# ---------------------------------------------------------------- true advances

def ttf_advances(path):
    """{codepoint: advance in font units} and the units per em, from a TTF's cmap and hmtx."""
    data = open(path, 'rb').read()
    n = struct.unpack('>H', data[4:6])[0]
    tables = {}
    for i in range(n):
        tag, _, off, length = struct.unpack('>4sIII', data[12 + 16 * i:28 + 16 * i])
        tables[tag.decode()] = (off, length)
    upm = struct.unpack('>H', data[tables['head'][0] + 18:tables['head'][0] + 20])[0]
    hmetrics = struct.unpack('>H', data[tables['hhea'][0] + 34:tables['hhea'][0] + 36])[0]
    hoff = tables['hmtx'][0]
    widths = [struct.unpack('>H', data[hoff + 4 * i:hoff + 4 * i + 2])[0] for i in range(hmetrics)]
    coff = tables['cmap'][0]
    count = struct.unpack('>H', data[coff + 2:coff + 4])[0]
    sub = None
    for i in range(count):
        pid, eid, off = struct.unpack('>HHI', data[coff + 4 + 8 * i:coff + 12 + 8 * i])
        fmt = struct.unpack('>H', data[coff + off:coff + off + 2])[0]
        if (pid, eid, fmt) in ((3, 10, 12), (0, 4, 12)) or (sub is None and fmt == 4 and pid in (0, 3)):
            sub = coff + off
    cmap = {}
    fmt = struct.unpack('>H', data[sub:sub + 2])[0]
    if fmt == 4:
        segs = struct.unpack('>H', data[sub + 6:sub + 8])[0] // 2
        ends = struct.unpack(f'>{segs}H', data[sub + 14:sub + 14 + 2 * segs])
        base = sub + 16 + 2 * segs
        starts = struct.unpack(f'>{segs}H', data[base:base + 2 * segs])
        deltas = struct.unpack(f'>{segs}h', data[base + 2 * segs:base + 4 * segs])
        roff = base + 4 * segs
        ranges = struct.unpack(f'>{segs}H', data[roff:roff + 2 * segs])
        for s in range(segs):
            for c in range(starts[s], ends[s] + 1):
                if c == 0xFFFF:
                    continue
                if ranges[s] == 0:
                    g = (c + deltas[s]) & 0xFFFF
                else:
                    at = roff + 2 * s + ranges[s] + 2 * (c - starts[s])
                    g = struct.unpack('>H', data[at:at + 2])[0]
                    g = (g + deltas[s]) & 0xFFFF if g else 0
                cmap[c] = g
    else:
        groups = struct.unpack('>I', data[sub + 12:sub + 16])[0]
        for i in range(groups):
            a, b, g0 = struct.unpack('>III', data[sub + 16 + 12 * i:sub + 28 + 12 * i])
            for c in range(a, b + 1):
                cmap[c] = g0 + c - a
    return {c: widths[min(g, hmetrics - 1)] for c, g in cmap.items()}, upm


def true_advance(units, upm, size):
    """The advance at a size in whole pixels, to the nearest, a half up."""
    return math.floor(units * size / upm + 0.5)


def fix_advances(directory):
    changed = 0
    for name in sorted(os.listdir(directory)):
        m = re.match(r'(.+)-(\d+)\.fnt$', name)
        if not m:
            continue
        adv, upm = ttf_advances(f'resources/fonts/{m.group(1)}.ttf')
        size = int(m.group(2))
        path = os.path.join(directory, name)
        text = open(path, encoding='utf-8').read()

        def repl(mm):
            nonlocal changed
            want = true_advance(adv[int(mm.group(1))], upm, size)
            changed += want != int(mm.group(3))
            return f"{mm.group(0)[:mm.start(3) - mm.start(0)]}{want}"
        text = re.sub(r'^char id=(\d+)\s(.*?)xadvance=(-?\d+)', repl, text, flags=re.M)
        open(path, 'w', encoding='utf-8').write(text)
    return changed


def main(argv):
    if argv[:1] == ['write']:
        doc = table()
        bad = problems(doc)
        if bad:
            sys.exit('\n'.join(f"{SIZES}: {b}" for b in bad))
        for path, make in OUTPUTS.items():
            with open(path, 'w', encoding='utf-8') as f:
                f.write(make(doc))
            print(f"wrote {path}")
    elif argv[:1] == ['advances'] and argv[1:]:
        for d in argv[1:]:
            print(f"{d}: {fix_advances(d)} advances set to the font's, rounded to the nearest pixel")
    else:
        sys.exit(__doc__.strip().splitlines()[2].strip() + '\n' + __doc__.strip().splitlines()[3].strip())


if __name__ == '__main__':
    main(sys.argv[1:])
